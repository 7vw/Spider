import assert from "node:assert/strict";
import fs from "fs";
import vm from "vm";

const engine = fs.readFileSync("js/kalima_engine.js", "utf8");
const context = { globalThis: {} };
vm.createContext(context);
vm.runInContext(engine, context);
const K = context.globalThis.KALIMA;

assert.equal(K.norm("أَسْتَاذَة"), "استاذه");
assert.equal(K.norm("مؤسسة"), "موسسه");
assert.equal(K.norm("شئون"), "شيون");
assert.equal(K.norm("على"), "علي");
assert.equal(K.norm("مَدْرَسَة"), "مدرسه");
assert.equal(K.score("مدرسه", "مدرسه"), "ggggg");
assert.equal(K.score("مدرسه", "سارحه"), "ybgbg");
const S = "\u0633", M = "\u0645", H = "\u0647";
assert.equal(K.score(S + M + S + M + H, M + S + M + S + M), "yyyyb");
assert.equal(K.score("كتابك", "ظنونظ"), "bbbbb");
assert.equal(K.dayIndex("2026-01-01", 400), 0);
assert.equal(K.dayIndex("2026-01-02", 400), 1);
assert.equal(K.dayIndex("2025-12-31", 400), 399);
assert.equal(K.prevDay("2026-03-01"), "2026-02-28");
assert.equal(K.prevDay("2028-03-01"), "2028-02-29");

const guesses = fs.readFileSync("js/kalima_guesses.js", "utf8");
const answers = fs.readFileSync("supabase/functions/spider/kalima_answers.js", "utf8");
assert.equal(guesses.includes("KALIMA_ANSWERS"), false);
const ans = [...answers.matchAll(/"([^"]+)"/g)].map(m => m[1]);
const gset = new Set([...guesses.matchAll(/"([^"]+)"/g)].map(m => m[1]));
assert.ok(ans.length >= 365);
assert.equal(ans.length, 400);
for (const w of ans) {
  assert.equal([...w].length, 5);
  assert.equal(gset.has(w), true);
  assert.equal(K.norm(w), w);
}
assert.equal(guesses.indexOf(ans.slice(0, 8).join(",")), -1);
const app = fs.readFileSync("app.js", "utf8");
const art = fs.readFileSync("artifact.html", "utf8");
const sw = fs.readFileSync("sw.js", "utf8");
for (const blob of [app, art, sw, guesses]) assert.equal(blob.includes("KALIMA_ANSWERS"), false);

const src = fs.readFileSync("supabase/functions/spider/index.ts", "utf8");
const pickStart = src.indexOf("/* @kalima-pick-start */");
const pickEnd = src.indexOf("/* @kalima-pick-end */");
assert.ok(pickStart > 0 && pickEnd > pickStart);
const pickSrc = src.slice(pickStart, pickEnd);
const pickCtx = { globalThis, crypto, TextEncoder, Uint8Array, Array, Math, process: { env: {} } };
vm.createContext(pickCtx);
vm.runInContext(pickSrc + "\nglobalThis.kalimaAnswer=kalimaAnswer;globalThis.kalimaSecretText=kalimaSecretText;globalThis.kalimaPerm=kalimaPerm;", pickCtx);
const SECRET = "test-secret-at-least-16";
const OTHER = "another-secret-value-16";
const a1 = await pickCtx.globalThis.kalimaAnswer(SECRET, "2026-10-20", ans);
const a2 = await pickCtx.globalThis.kalimaAnswer(SECRET, "2026-10-20", ans);
const b1 = await pickCtx.globalThis.kalimaAnswer(SECRET, "2026-10-21", ans);
const c1 = await pickCtx.globalThis.kalimaAnswer(OTHER, "2026-10-20", ans);
assert.equal(a1, a2);
assert.notEqual(a1, b1);
assert.notEqual(a1, c1);
assert.equal(ans.includes(a1), true);
assert.equal(ans.includes(b1), true);
assert.equal(pickCtx.globalThis.kalimaSecretText("too-short", { s: SECRET }), SECRET);
assert.equal(pickCtx.globalThis.kalimaSecretText("", { secret: SECRET }), SECRET);
assert.equal(pickCtx.globalThis.kalimaSecretText("", null), "");
assert.equal(pickCtx.globalThis.kalimaSecretText("short-secret", null), "");
const ordered = ans[K.dayIndex("2026-10-20", ans.length)];
assert.notEqual(a1, ordered);
const riyadh = ms => new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Riyadh", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(ms));
assert.equal(riyadh(Date.parse("2026-10-20T20:59:00Z")), "2026-10-20");
assert.equal(riyadh(Date.parse("2026-10-20T21:00:00Z")), "2026-10-21");
const start = src.slice(src.indexOf('case "word_start"'), src.indexOf('case "word_guess"'));
const guess = src.slice(src.indexOf('case "word_guess"'), src.indexOf("fail(\"bad\",\"طلب غير معروف\")"));
assert.equal(start.includes("disabled:true"), true);
assert.equal(start.includes("answer"), false);
assert.equal(guess.includes("answer:"), false);
assert.equal(/return \{[^}]*answer/.test(guess), false);
assert.equal(guess.includes("كلمة اليوم غير مفعّلة"), true);
assert.equal(guess.includes("kalimaAnswer"), true);
assert.equal(guess.includes("KALIMA.dayIndex"), false);
assert.equal(app.includes("كلمة اليوم غير مفعّلة على الخادم."), true);
console.log("ok kalima engine", ans.length, "answers", gset.size, "guesses", "hmac", a1, b1);
